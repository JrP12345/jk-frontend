// @vitest-environment node
import fs from "node:fs";
import ts from "typescript";
import { createHash } from "node:crypto";
import { PHARMACY_OFFLINE_FILES, PHARMACY_OFFLINE_CACHE } from "@/lib/pharmacyOfflineAssets";
import { expect, it } from "vitest";
it("ships the current pure pharmacy draft/catalogue code in the public offline shell", () => {
  const files: Array<[string, string]> = JSON.parse(fs.readFileSync("scripts/pharmacy-offline-files.json", "utf8"));
  const modules = new Map(files.map(([source, target]) => [source.split("/").at(-1)!.replace(/\.ts$/, ""), target]));
  for (const [source, target] of files) {
    const { outputText } = ts.transpileModule(fs.readFileSync(source, "utf8"), { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2020, removeComments: true } });
    const output = outputText.replace(/from ["']([^"']+)["']/g, (_, value: string) => `from "./${modules.get(value.split("/").at(-1)!.replace(/\.ts$/, ""))}"`);
    const shipped = fs.readFileSync(`public/pharmacy-offline/${target}`, "utf8");
    expect(shipped).toBe(`// Generated by scripts/build-pharmacy-offline.mjs\n${output}`);
    expect(shipped).not.toMatch(/axios|\/collections|razorpay|patientName|cardNumber/);
    expect(shipped).not.toMatch(/fetch\("\/api\/pharmacy\/sales"/);
  }
  expect(fs.readFileSync("public/pharmacy-offline.html", "utf8")).not.toMatch(/<script[^>]*>[^<]+<\/script>|on(click|load)=/);
  const worker = fs.readFileSync("public/sw.js", "utf8"); expect(worker).toContain(PHARMACY_OFFLINE_CACHE);
  const manifest = JSON.parse(fs.readFileSync("public/pharmacy-offline/manifest.json", "utf8"));
  expect(manifest.files.map((file: { path: string }) => file.path).sort()).toEqual([...PHARMACY_OFFLINE_FILES].sort());
  for (const file of manifest.files) {
    expect(createHash("sha256").update(fs.readFileSync(`public${file.path}`)).digest("hex")).toBe(file.sha256);
    expect(worker).toContain(file.path);
  }
});
