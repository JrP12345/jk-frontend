import fs from 'node:fs/promises';
import ts from 'typescript';
import { createHash } from 'node:crypto';
const files = JSON.parse(await fs.readFile(new URL('./pharmacy-offline-files.json', import.meta.url), 'utf8'));
const modules = new Map(files.map(([input, output]) => [input.split('/').at(-1).replace(/\.ts$/, ''), output]));
await fs.mkdir('public/pharmacy-offline', { recursive: true });
for (const [input, name] of files) {
  const source = await fs.readFile(input, 'utf8');
  const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2020, removeComments: true } });
  const output = outputText.replace(/from ["']([^"']+)["']/g, (_, specifier) => {
    const name = modules.get(specifier.split('/').at(-1).replace(/\.ts$/, ''));
    if (!specifier.startsWith('.') || !name) throw Error(`Offline module has a non-public dependency: ${input}`);
    return `from "./${name}"`;
  });
  if (/from ["'](?:@\/|\.\.\/)/.test(output)) throw Error(`Offline bundle contains an unresolved import: ${input}`);
  await fs.writeFile(`public/pharmacy-offline/${name}`, `// Generated by scripts/build-pharmacy-offline.mjs\n${output}`);
}
const paths = ['/pharmacy-offline.html', '/pharmacy-offline.css', ...files.map(([, output]) => `/pharmacy-offline/${output}`)];
for (const resource of ['/pharmacy-offline.html', '/pharmacy-offline.css']) {
  const filename = `public${resource}`, source = await fs.readFile(filename, 'utf8');
  if (source.includes('\r')) await fs.writeFile(filename, source.replace(/\r\n/g, '\n'));
}
const assetSource = await fs.readFile('src/lib/pharmacyOfflineAssets.ts', 'utf8');
const allowed = [...assetSource.match(/PHARMACY_OFFLINE_FILES = \[([\s\S]*?)\] as const/)[1].matchAll(/"([^"]+)"/g)].map(match => match[1]);
if (JSON.stringify([...paths].sort()) !== JSON.stringify([...allowed].sort())) throw Error('Offline asset installation allowlist differs from generated resources.');
const calculation = (await fs.readFile('src/lib/generated/pharmacyCalculation.ts', 'utf8')).match(/PHARMACY_CALCULATION_ENGINE_SHA256 = "([a-f0-9]{64})"/)[1];
const document = (await fs.readFile('src/lib/generated/pharmacyOfflineDocument.ts', 'utf8')).match(/PHARMACY_OFFLINE_DOCUMENT_SHA256 = "([a-f0-9]{64})"/)[1];
const manifest = { version: 1, calculation, document, files: [] };
for (const resource of paths) manifest.files.push({ path: resource, sha256: createHash('sha256').update(await fs.readFile(`public${resource}`)).digest('hex') });
await fs.writeFile('public/pharmacy-offline/manifest.json', JSON.stringify(manifest));
const worker = await fs.readFile('public/sw.js', 'utf8');
await fs.writeFile('public/sw.js', worker.replace(/const POS_FILES = \[[^\n]*\];/, `const POS_FILES = ${JSON.stringify([...paths, '/pharmacy-offline/manifest.json'])};`));
