// The backend pure utility is the single edited source. Generated browser code
// is committed so frontend builds need no sibling checkout or runtime fetch.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const sourceUrl = new URL('../../backend/utilities/pharmacyCalculation.ts', import.meta.url);
const targetUrl = new URL('../src/lib/generated/pharmacyCalculation.ts', import.meta.url);
const versionUrl = new URL('../../backend/utilities/pharmacyCalculationVersion.ts', import.meta.url);
const source = (await fs.readFile(sourceUrl, 'utf8')).replace(/\r\n/g, '\n');
if (/^import\s/m.test(source)) throw Error('Shared pharmacy calculation must have no runtime dependencies.');
const sha256 = createHash('sha256').update(source).digest('hex');
const output = `// Generated by scripts/sync-pharmacy-calculation.mjs; edit backend/utilities/pharmacyCalculation.ts.\nexport const PHARMACY_CALCULATION_ENGINE_SHA256 = "${sha256}" as const;\n${source}`;
const version = `// Generated by frontend/scripts/sync-pharmacy-calculation.mjs.\nexport const PHARMACY_CALCULATION_ENGINE_SHA256 = "${sha256}" as const;\n`;
if (process.argv.includes('--check')) {
  if (await fs.readFile(targetUrl, 'utf8') !== output) throw Error('Shared pharmacy calculation changed; regenerate the browser artifact.');
  if (await fs.readFile(versionUrl, 'utf8') !== version) throw Error('Server pharmacy calculation digest changed; regenerate the version.');
} else {
  await fs.mkdir(new URL('../src/lib/generated/', import.meta.url), { recursive: true });
  await fs.writeFile(targetUrl, output);
  await fs.writeFile(versionUrl, version);
}
const documentSourceUrl = new URL('../../backend/utilities/pharmacyOfflineDocument.ts', import.meta.url);
const documentTargetUrl = new URL('../src/lib/generated/pharmacyOfflineDocument.ts', import.meta.url);
const documentVersionUrl = new URL('../../backend/utilities/pharmacyOfflineDocumentVersion.ts', import.meta.url);
const documentSource = (await fs.readFile(documentSourceUrl, 'utf8')).replace(/\r\n/g, '\n');
const documentHash = createHash('sha256').update(documentSource).digest('hex');
const documentOutput = `// Generated by scripts/sync-pharmacy-calculation.mjs; edit backend/utilities/pharmacyOfflineDocument.ts.\nexport const PHARMACY_OFFLINE_DOCUMENT_SHA256 = "${documentHash}" as const;\n${documentSource.replace('from "./pharmacyCalculation.ts"', 'from "./pharmacyCalculation"')}`;
const documentVersion = `// Generated by frontend/scripts/sync-pharmacy-calculation.mjs.\nexport const PHARMACY_OFFLINE_DOCUMENT_SHA256 = "${documentHash}" as const;\n`;
if (process.argv.includes('--check')) {
  if (await fs.readFile(documentTargetUrl, 'utf8') !== documentOutput || await fs.readFile(documentVersionUrl, 'utf8') !== documentVersion) throw Error('Shared offline document source changed; regenerate the browser artifact.');
} else {
  await fs.writeFile(documentTargetUrl, documentOutput);
  await fs.writeFile(documentVersionUrl, documentVersion);
}
